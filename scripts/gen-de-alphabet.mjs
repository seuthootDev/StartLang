/**
 * Generate German alphabet quiz + reference table.
 * A–Z German letter names + Ä Ö Ü ß; digraphs as reference only.
 * Run: node scripts/gen-de-alphabet.mjs
 *
 * German differs from Romance packs:
 * - Letter names are Germanic (ah, jot, fau, tsett…), not bi/ci-style.
 * - Extra letters: umlauts + Eszett (not accent-marked stress vowels).
 * - Digraphs (ch, sch, ei…) matter early for reading — table section, not quiz.
 */
import { writeFileSync, mkdirSync } from 'fs'
